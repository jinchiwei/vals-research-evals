"""Narration: synthesise each segment with Kokoro-82M (offline), place it on the scene timeline, mux.

Scene starts come from the JSON block in index.src.html (disabled scenes skipped unless --with),
so adding or resizing a scene moves the narration with it.

Usage (vals-demo env, HF_HOME inside the env):
  python narrate.py                 # check timing, write narration.md, audio/narration.wav, demo-narrated.mp4
  python narrate.py --with models   # include a disabled scene (video must be rendered with the same flag)
  python narrate.py --check-only    # synthesise and report timing, no mux
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FFMPEG = "/usr/bin/ffmpeg"
SR = 24000
os.environ.setdefault("HF_HOME", str(Path(sys.executable).resolve().parent.parent / "hf-home"))


def scene_table(with_ids):
    src = (HERE / "index.src.html").read_text(encoding="utf-8")
    m = re.search(r'<script type="application/json" id="data">(.*?)</script>', src, re.S)
    data = json.loads(m.group(1))
    out, t = [], 0.0
    for s in data["scenes"]:
        if s.get("enabled", True) is False and s["id"] not in with_ids:
            continue
        out.append({"id": s["id"], "start": t, "end": t + s["dur"], "dur": s["dur"]})
        t += s["dur"]
    return out, t


def synth(pipe, text, voice, speed, cache):
    import numpy as np
    import soundfile as sf

    key = hashlib.sha1(f"{voice}|{speed}|{text}".encode()).hexdigest()[:16]
    f = cache / f"{key}.wav"
    if not f.exists():
        audio = np.concatenate([r.audio.numpy() for r in pipe(text, voice=voice, speed=speed)])
        sf.write(f, audio, SR)
    a, _ = sf.read(f, dtype="float32")
    return a


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--with", dest="with_ids", default="")
    ap.add_argument("--check-only", action="store_true")
    ap.add_argument("--video", default=str(HERE / "demo.mp4"))
    ap.add_argument("--out", default=str(HERE / "demo-narrated.mp4"))
    args = ap.parse_args()
    with_ids = [s for s in args.with_ids.split(",") if s]

    import numpy as np
    import soundfile as sf
    from kokoro import KPipeline

    cfg = json.loads((HERE / "narration.json").read_text(encoding="utf-8"))
    scenes, total = scene_table(with_ids)
    pipe = KPipeline(lang_code=cfg["lang_code"], repo_id="hexgrad/Kokoro-82M")
    cache = HERE / "audio" / "clips"
    cache.mkdir(parents=True, exist_ok=True)

    track = np.zeros(int(round(total * SR)) + SR, dtype=np.float32)
    rows, problems, md = [], [], []
    last_abs_end = -1.0
    for sc in scenes:
        segs = cfg["scenes"].get(sc["id"], [])
        md.append(f"\n## {sc['id']} — starts {sc['start']:.1f} s ({sc['dur']} s scene)\n")
        prev_local_end = -1e9
        for k, (anchor, text) in enumerate(segs):
            next_anchor = segs[k + 1][0] if k + 1 < len(segs) else None
            a = synth(pipe, text, cfg["voice"], cfg["speed"], cache)
            dur = len(a) / SR
            local = max(anchor, prev_local_end + cfg["min_gap_s"])
            end = local + dur
            ok = end <= sc["dur"] - cfg["scene_tail_s"]
            t0 = sc["start"] + local
            if t0 < last_abs_end + cfg["min_gap_s"] - 1e-6:
                problems.append(f"{sc['id']}: overlaps previous clip")
            if sc['id'] in cfg.get('strict_scenes', []) and next_anchor is not None and end > next_anchor - 0.1:
                problems.append(f"{sc['id']}: '{text[:40]}…' ends at {end:.2f} s, after the next anchor {next_anchor} s (drift)")
            if not ok:
                problems.append(f"{sc['id']}: '{text[:40]}…' ends at {end:.2f} s of {sc['dur']} s")
            i0 = int(round(t0 * SR))
            track[i0:i0 + len(a)] += a
            prev_local_end, last_abs_end = end, t0 + dur
            words = len(text.split())
            rows.append((sc["id"], t0, t0 + dur, dur, words, ok))
            md.append(f"- **{t0:6.1f}–{t0 + dur:5.1f} s** (scene +{local:.1f} s, {dur:.1f} s, {words} words, "
                      f"{60 * words / dur:.0f} wpm): {text}")

    for sid, a, b, d, w, ok in rows:
        print(f"{sid:10s} {a:6.2f}–{b:6.2f}  {d:5.2f} s  {w:3d} words  {'ok' if ok else 'TOO LONG'}")
    spoken = sum(r[3] for r in rows)
    print(f"total video {total:.1f} s; speech {spoken:.1f} s; {sum(r[4] for r in rows)} words")
    if problems:
        print("PROBLEMS:\n  " + "\n  ".join(problems))
        return 1

    head = ["# Narration script", "",
            f"Voice: Kokoro-82M `{cfg['voice']}` (Apache-2.0), speed {cfg['speed']}. Generated by `narrate.py` "
            "from `narration.json`; times are seconds into the video. Edit `narration.json`, not this file.",
            f"Video length {total:.1f} s; scenes: " + ", ".join(f"{s['id']} {s['start']:.0f} s" for s in scenes) + "."]
    (HERE / "narration.md").write_text("\n".join(head + md) + "\n", encoding="utf-8")
    wav = HERE / "audio" / "narration.wav"
    sf.write(wav, track[: int(round(total * SR))], SR)
    if args.check_only:
        return 0
    # Two-pass loudness normalisation to -14 LUFS integrated, -1.5 dBTP.
    target = "I=-14:TP=-1.5:LRA=11"
    probe = subprocess.run([FFMPEG, "-hide_banner", "-nostats", "-i", str(wav), "-af",
                            f"loudnorm={target}:print_format=json", "-f", "null", "-"],
                           capture_output=True, text=True, check=True).stderr
    meas = json.loads(probe[probe.rindex("{"):probe.rindex("}") + 1])
    af = (f"loudnorm={target}:measured_I={meas['input_i']}:measured_TP={meas['input_tp']}"
          f":measured_LRA={meas['input_lra']}:measured_thresh={meas['input_thresh']}"
          f":offset={meas['target_offset']}:linear=true")
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", args.video, "-i", str(wav),
                    "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy",
                    "-af", af, "-ar", "48000", "-ac", "2",
                    "-c:a", "aac", "-b:a", "160k", "-t", f"{total:.3f}", "-movflags", "+faststart", args.out],
                   check=True)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
