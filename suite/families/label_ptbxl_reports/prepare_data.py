"""Build the label_ptbxl_reports split from the PTB-XL 1.0.3 copy staged for ecg_ptbxl (read-only).

Design (docs/research/suite/label_ptbxl_reports.md, fixed before any comparator or agent run):
- Eligible: validated_by_human == True, initial_autogenerated_report == False (the report string was
  written by a cardiologist, not the device), at least one diagnostic superclass under the standard
  rule (every SCP code with diagnostic == 1 maps to its diagnostic_class, whatever its likelihood),
  and a report with textual content (not empty, not the placeholder 'trace only requested').
- Fold 10 is never used: it holds the ecg_ptbxl hidden cases (and their patients).
- Hidden: HIDDEN_N records from fold 9 (never agent-visible in ecg_ptbxl; 100 % human-validated),
  proportional stratified sample over the 5-label combination (rare combinations pooled).
- Development: DEV_N records from folds 1-8 (patient-disjoint from fold 9 by construction).
- Records get random IDs; the crosswalk to ecg_id is written to work/ and never shipped.

Usage: python prepare_data.py SRC_DIR OUT_DIR
"""
import ast
import csv
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

SEED = 20261114
CLASSES = ('NORM', 'MI', 'STTC', 'CD', 'HYP')
HIDDEN_N = 500
DEV_N = 2000
RARE_STRATUM = 10          # label combinations with fewer eligible records are pooled
PLACEHOLDER = re.compile(r'trace\s+only\s+requested', re.I)
LABEL_RULE = ('every SCP code with diagnostic == 1 maps to its diagnostic_class, whatever its likelihood '
              '(PTB-XL benchmark rule, Strodthoff et al. 2021)')


def superclasses(scp_codes, diag):
    return sorted({diag[k] for k in ast.literal_eval(scp_codes) if k in diag}, key=CLASSES.index)


def has_text(report):
    r = str(report) if isinstance(report, str) else ''
    return len(re.findall(r'[^\W\d_]', r)) >= 3 and not PLACEHOLDER.search(r)


def stratified_sample(frame, n, rng):
    """Proportional allocation over label combinations (largest remainder), rare ones pooled."""
    combo = frame['labels'].apply(lambda l: '+'.join(l))
    counts = combo.value_counts()
    stratum = combo.where(combo.map(counts) >= RARE_STRATUM, 'RARE')
    sizes = stratum.value_counts().sort_index()
    exact = sizes / sizes.sum() * n
    alloc = np.floor(exact).astype(int)
    order = (exact - alloc).sort_values(ascending=False, kind='stable').index
    for key in order[: n - alloc.sum()]:
        alloc[key] += 1
    picked = []
    for key in sorted(sizes.index):
        idx = np.sort(frame.index[stratum == key].to_numpy())
        picked += list(rng.choice(idx, size=int(alloc[key]), replace=False))
    return frame.loc[sorted(picked)]


def sha(ids):
    return hashlib.sha256('\n'.join(sorted(ids)).encode()).hexdigest()


def main(src, out):
    src, out = Path(src), Path(out)
    db = pd.read_csv(src / 'ptbxl_database.csv')
    st = pd.read_csv(src / 'scp_statements.csv', index_col=0)
    diag = st[st.diagnostic == 1].diagnostic_class.to_dict()
    db['labels'] = db.scp_codes.apply(lambda x: superclasses(x, diag))
    checks = {'records': len(db)}
    m_val = db.validated_by_human.astype(bool)
    m_auto = db.initial_autogenerated_report.astype(bool)
    m_lab = db['labels'].str.len() > 0
    m_txt = db.report.apply(has_text)
    m_fold = db.strat_fold <= 9
    checks['excluded'] = {
        'fold_10 (ecg_ptbxl hidden fold)': int((~m_fold).sum()),
        'not validated_by_human (folds 1-9)': int((m_fold & ~m_val).sum()),
        'validated but initial_autogenerated_report (folds 1-9)': int((m_fold & m_val & m_auto).sum()),
        'no diagnostic superclass (after above)': int((m_fold & m_val & ~m_auto & ~m_lab).sum()),
        'no textual content, e.g. trace only requested (after above)': int((m_fold & m_val & ~m_auto & m_lab & ~m_txt).sum()),
    }
    el = db[m_fold & m_val & ~m_auto & m_lab & m_txt].copy()
    checks['eligible_by_fold'] = {int(k): int(v) for k, v in el.groupby('strat_fold').size().items()}
    rng = np.random.default_rng(SEED)
    hidden = stratified_sample(el[el.strat_fold == 9], HIDDEN_N, rng)
    dev = stratified_sample(el[el.strat_fold <= 8], DEV_N, rng)
    assert not set(hidden.patient_id) & set(dev.patient_id)
    # Random IDs, unique across both roles, drawn from the same seeded stream.
    tokens = []                # a list, not a set: set order depends on PYTHONHASHSEED
    while len(tokens) < len(hidden) + len(dev):
        t = 'r' + rng.integers(0, 16**8).item().to_bytes(4, 'big').hex()
        if t not in tokens:
            tokens.append(t)
    hidden = hidden.assign(record_id=tokens[:len(hidden)])
    dev = dev.assign(record_id=tokens[len(hidden):])

    work = out / 'work'
    pub = work / 'public'
    ref = work / 'hidden' / 'reference'
    for d in (pub, ref):
        d.mkdir(parents=True, exist_ok=True)

    def clean(r):
        return re.sub(r'\s+', ' ', r).strip()

    dev_rows = dev.sort_values('record_id')
    with open(pub / 'dev_reports.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['record_id', 'report', *CLASSES])
        for _, r in dev_rows.iterrows():
            w.writerow([r.record_id, clean(r.report), *[int(c in r['labels']) for c in CLASSES]])
    hid_rows = hidden.sort_values('record_id')
    with open(pub / 'hidden_reports.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['record_id', 'report'])
        for _, r in hid_rows.iterrows():
            w.writerow([r.record_id, clean(r.report)])
    # Labelling guide: the 44 diagnostic statements and their superclass (no record-level data).
    guide = st[st.diagnostic == 1][['description', 'Statement Category', 'diagnostic_class', 'diagnostic_subclass']]
    guide = guide.reset_index().rename(columns={'index': 'scp_code', 'Statement Category': 'category',
                                                'diagnostic_class': 'superclass', 'diagnostic_subclass': 'subclass'})
    guide.sort_values(['superclass', 'scp_code']).to_csv(pub / 'diagnostic_statements.csv', index=False)
    labels = {r.record_id: list(r['labels']) for _, r in hid_rows.iterrows()}
    (ref / 'labels.json').write_text(json.dumps(labels, indent=1, sort_keys=True) + '\n')
    pd.concat([hid_rows.assign(role='hidden'), dev_rows.assign(role='dev')])[['record_id', 'ecg_id', 'patient_id',
                                                                               'strat_fold', 'role']].to_csv(
        work / 'crosswalk.csv', index=False)

    def prev(frame):
        c = Counter(k for l in frame['labels'] for k in l)
        return {k: round(c[k] / len(frame), 4) for k in CLASSES}

    lang = {'german': r'sinusrhythmus|lagetyp|ekg\b|infarkt|linkstyp|rechtstyp|hypertroph|st-senkung',
            'swedish': r'sinusrytm|fÖrmak|vÄnster|myokardaffektion|normalt ekg'}
    splits = {'seed': SEED, 'classes': list(CLASSES), 'label_rule': LABEL_RULE,
              'hidden': {'source': 'fold 9, eligible, stratified', 'n': len(hid_rows),
                         'patients': int(hid_rows.patient_id.nunique()), 'sha256_sorted_ecg_ids':
                             sha([str(x) for x in hid_rows.ecg_id]), 'sha256_sorted_record_ids': sha(hid_rows.record_id),
                         'prevalence': prev(hid_rows), 'ecg_ids': sorted(int(x) for x in hid_rows.ecg_id)},
              'dev': {'source': 'folds 1-8, eligible, stratified', 'n': len(dev_rows),
                      'patients': int(dev_rows.patient_id.nunique()),
                      'sha256_sorted_ecg_ids': sha([str(x) for x in dev_rows.ecg_id]),
                      'sha256_sorted_record_ids': sha(dev_rows.record_id), 'prevalence': prev(dev_rows),
                      'ecg_ids': sorted(int(x) for x in dev_rows.ecg_id)}}
    for role, frame in (('hidden', hid_rows), ('dev', dev_rows)):
        rep = frame.report.str.lower()
        g = rep.str.contains(lang['german'])
        s = rep.str.contains(lang['swedish']) & ~g
        splits[role]['language_heuristic'] = {'german': round(float(g.mean()), 3), 'swedish': round(float(s.mean()), 3),
                                              'other_mostly_english': round(float((~g & ~s).mean()), 3)}
        splits[role]['n_labels'] = {int(k): int(v) for k, v in frame['labels'].str.len().value_counts().sort_index().items()}
        splits[role]['second_opinion_edit'] = int(frame.second_opinion.sum())
    dev_text = set(dev_rows.report.map(clean))
    splits['hidden']['exact_text_in_dev'] = int(hid_rows.report.map(clean).isin(dev_text).sum())
    (work / 'splits.json').write_text(json.dumps(splits, indent=1) + '\n')
    (work / 'data_checks.json').write_text(json.dumps(checks, indent=1) + '\n')
    print(json.dumps({k: v for k, v in splits.items() if k not in ('hidden', 'dev')}, indent=1))
    for role in ('hidden', 'dev'):
        print(role, {k: v for k, v in splits[role].items() if k != 'ecg_ids'})
    print(json.dumps(checks, indent=1))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
