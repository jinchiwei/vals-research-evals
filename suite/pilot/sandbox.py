"""Bubblewrap sandboxes and the host-side egress proxy for local suite pilots.

Two sandboxes, both built from an empty root (nothing from the host appears unless bound):

* agent sandbox: read-only /usr (+ /bin, /lib, /lib64, /sbin symlinks) and /etc, the task
  runtime at /opt/benchmark-venv (read-only), the agent CLI at /opt/agent/<name> (read-only),
  a fresh writable HOME at /home/agent, a writable /workspace with the public data bound
  read-only at /workspace/data, private /tmp, /proc and /dev. New PID, IPC, UTS and cgroup
  namespaces. Egress "proxy": a new network namespace (loopback only) plus an in-sandbox relay
  to a host proxy that only CONNECTs to allowlisted hosts on port 443. Egress "open": host
  network (general internet reachable).
* pipeline sandbox (grading): same read-only system dirs and runtime, the staged pipeline at
  /eval/pipeline (read-only), one case's input at /eval/in/<case> (read-only), its output and
  home writable, the agent's /workspace/output and the public /workspace/data read-only (the
  hosted verifier image has both), and --unshare-all: no network at all, new user namespace.
  The tests tree (hidden references, specialist outputs) is never bound.

Non-root limits: the pipeline runs under the invoking uid inside a user namespace (no switch
to uid 65534 as the hosted root verifier does); isolation is by mount namespace instead.
"""
import json
import os
import shlex
import socket
import threading
import time
from pathlib import Path

BWRAP = '/usr/bin/bwrap'
VENV = '/opt/benchmark-venv'
SYSTEM_RO = ('/usr', '/etc')
USR_MERGED = ('bin', 'lib', 'lib64', 'sbin')
PROXY_PORT = 18080


def system_binds():
    args = []
    for path in SYSTEM_RO:
        args += ['--ro-bind', path, path]
    for name in USR_MERGED:
        p = Path('/') / name
        if p.is_symlink():
            args += ['--symlink', os.readlink(p), str(p)]
        elif p.is_dir():
            args += ['--ro-bind', str(p), str(p)]
    return args


def agent_command(*, workspace, data_dir, home, runtime_prefix, agent_bin, agent_name, command,
                  egress, proxy_socket=None, relay_script=None, extra_ro=()):
    """bwrap argv for the agent. `command` is the agent argv using /opt/agent/<agent_name>."""
    args = [BWRAP, '--die-with-parent', '--unshare-pid', '--unshare-ipc', '--unshare-uts',
            '--unshare-cgroup-try', '--hostname', 'agent-sandbox']
    if egress == 'proxy':
        args += ['--unshare-net']
    args += system_binds()
    if egress == 'open':
        dns = Path('/etc/resolv.conf').resolve()       # WSL points this outside /etc
        if str(dns) != '/etc/resolv.conf' and dns.exists():
            args += ['--ro-bind', str(dns), str(dns)]
    args += ['--proc', '/proc', '--dev', '/dev', '--tmpfs', '/tmp', '--tmpfs', '/opt',
             '--ro-bind', str(runtime_prefix), VENV,
             '--ro-bind', str(agent_bin), f'/opt/agent/{agent_name}',
             '--bind', str(home), '/home/agent',
             '--bind', str(workspace), '/workspace',
             '--ro-bind', str(data_dir), '/workspace/data']
    for src, dst in extra_ro:
        args += ['--ro-bind', str(src), dst]
    if egress == 'proxy':
        args += ['--dir', '/run/egress', '--bind', str(proxy_socket), '/run/egress/egress.sock',
                 '--ro-bind', str(relay_script), '/opt/pilot/relay.py']
        command = ['/usr/bin/python3', '-I', '-S', '/opt/pilot/relay.py', '/run/egress/egress.sock',
                   str(PROXY_PORT), '--', *command]
    args += ['--chdir', '/workspace', '--']
    return args + list(command)


def agent_env(extra=None, threads=None, egress='proxy'):
    env = {'PATH': f'{VENV}/bin:/usr/local/bin:/usr/bin:/bin', 'HOME': '/home/agent', 'USER': 'agent',
           'TMPDIR': '/tmp', 'LANG': 'C.UTF-8', 'TERM': 'dumb', 'VIRTUAL_ENV': VENV,
           'PYTHONDONTWRITEBYTECODE': '1', 'PIP_NO_INDEX': '1', 'PIP_DISABLE_PIP_VERSION_CHECK': '1'}
    if threads:
        for name in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'ITK_GLOBAL_DEFAULT_NUMBER_OF_THREADS'):
            env[name] = str(int(threads))
    if egress == 'proxy':
        url = f'http://127.0.0.1:{PROXY_PORT}'
        env.update(HTTPS_PROXY=url, https_proxy=url, HTTP_PROXY=url, http_proxy=url)
    env.update(extra or {})
    return env


SHIM = r'''#!/bin/bash
# Local-pilot shim (not agent code): run the agent's pipeline in a no-network bubblewrap sandbox
# that cannot see the verifier's tests tree. Generated by suite/pilot/sandbox.py.
set -u
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
IN="$(cd "$1" && pwd)"
OUT="$(cd "$2" && pwd)"
CASE="$(basename "$IN")"
exec {bwrap} --unshare-all --die-with-parent --hostname verifier-sandbox \
  {system} \
  --proc /proc --dev /dev --tmpfs /tmp --tmpfs /opt --ro-bind {runtime} {venv} \
  --dir /workspace --ro-bind {data} /workspace/data {output} \
  --dir /eval --dir /eval/in --dir /eval/out --dir /eval/home \
  --ro-bind "$HERE/agent" /eval/pipeline \
  --ro-bind "$IN" "/eval/in/$CASE" --bind "$OUT" "/eval/out/$CASE" --bind "$HOME" "/eval/home/$CASE" \
  --setenv HOME "/eval/home/$CASE" --setenv TMPDIR "/eval/home/$CASE/tmp" \
  --setenv MPLCONFIGDIR "/eval/home/$CASE/tmp" --chdir "/eval/home/$CASE" \
  -- /bin/bash /eval/pipeline/run.sh "/eval/in/$CASE" "/eval/out/$CASE"
'''


def write_pipeline_shim(shim_dir, *, runtime_prefix, data_dir, agent_output_dir=None):
    """shim_dir/run.sh wraps shim_dir/agent/run.sh (caller copies the agent pipeline there)."""
    q = shlex.quote
    output = ''
    if agent_output_dir is not None and Path(agent_output_dir).is_dir():
        output = f'--ro-bind {q(str(agent_output_dir))} /workspace/output'
    text = SHIM.format(bwrap=BWRAP, system=' '.join(q(a) for a in system_binds()), runtime=q(str(runtime_prefix)),
                       venv=VENV, data=q(str(data_dir)), output=output)
    shim_dir = Path(shim_dir)
    shim_dir.mkdir(parents=True, exist_ok=True)
    (shim_dir / 'run.sh').write_text(text)
    (shim_dir / 'run.sh').chmod(0o755)
    return shim_dir / 'run.sh'


class EgressProxy:
    """Host-side HTTP CONNECT proxy on a unix socket; only allowlisted host:443 is tunnelled."""

    def __init__(self, sock_path, allowed_hosts, port=443):
        self.sock_path = str(sock_path)
        self.allowed = {h.lower() for h in allowed_hosts}
        self.port = port
        self.events = []
        self._lock = threading.Lock()
        self._listener = None

    def start(self):
        self._listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self._listener.bind(self.sock_path)
        os.chmod(self.sock_path, 0o600)
        self._listener.listen(64)
        threading.Thread(target=self._accept, daemon=True).start()
        return self

    def stop(self):
        if self._listener is not None:
            try:
                self._listener.close()
            except OSError:
                pass
        try:
            os.unlink(self.sock_path)
        except OSError:
            pass

    def _record(self, **event):
        event['t'] = round(time.time(), 3)
        with self._lock:
            if len(self.events) < 5000:
                self.events.append(event)

    def _accept(self):
        while True:
            try:
                conn, _ = self._listener.accept()
            except OSError:
                return
            threading.Thread(target=self._handle, args=(conn,), daemon=True).start()

    def _handle(self, conn):
        conn.settimeout(30)
        head = b''
        try:
            while b'\r\n\r\n' not in head and len(head) < 16384:
                chunk = conn.recv(4096)
                if not chunk:
                    break
                head += chunk
            line = head.split(b'\r\n', 1)[0].decode('latin-1')
            parts = line.split()
            method, target = (parts[0], parts[1]) if len(parts) >= 2 else ('', '')
            host, _, port = target.rpartition(':')
            host = host.strip('[]').lower()
            ok = method == 'CONNECT' and host in self.allowed and port == str(self.port)
            self._record(method=method[:16], host=host[:255] if method == 'CONNECT' else target[:255],
                         port=port[:8], allowed=ok)
            if not ok:
                conn.sendall(b'HTTP/1.1 403 Forbidden\r\nContent-Length: 0\r\nConnection: close\r\n\r\n')
                conn.close()
                return
            upstream = socket.create_connection((host, int(port)), timeout=30)
            conn.sendall(b'HTTP/1.1 200 Connection established\r\n\r\n')
            rest = head.split(b'\r\n\r\n', 1)[1]
            if rest:
                upstream.sendall(rest)
            conn.settimeout(None)
            upstream.settimeout(None)
        except (OSError, ValueError):
            try:
                conn.close()
            except OSError:
                pass
            return
        threading.Thread(target=_pump, args=(conn, upstream), daemon=True).start()
        threading.Thread(target=_pump, args=(upstream, conn), daemon=True).start()

    def summary(self):
        with self._lock:
            events = list(self.events)
        hosts = {}
        for e in events:
            key = f"{e['host']}:{e['port']}" if e.get('method') == 'CONNECT' else f"{e.get('method')} {e['host']}"
            row = hosts.setdefault(key, {'allowed': 0, 'denied': 0})
            row['allowed' if e['allowed'] else 'denied'] += 1
        return {'allowlist': sorted(self.allowed), 'port': self.port, 'connections': len(events), 'by_target': hosts}


def _pump(src, dst):
    try:
        while True:
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)
    except OSError:
        pass
    finally:
        for s in (src, dst):
            try:
                s.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass


def dump(path, data):
    Path(path).write_text(json.dumps(data, indent=2, sort_keys=True, default=str) + '\n')
